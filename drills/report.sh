#!/usr/bin/env bash
# Game-day report: turns the drill event log + CloudWatch alarm history into
# docs/gameday/<date>.md (commit it as evidence).
# Memory hook - "WHEN-WHAT-HOW LONG": when each drill started, what alarms fired, how long to
# detect and recover, plus RTO/RPO results from rto-watch / promote / failback.
#
# Usage: drills/report.sh [since]     since = ISO time or "today" (default: first event in the log)
. "$(dirname "$0")/../scripts/lib.sh"

LOG="$REPO_ROOT/.gameday/events.log"
[[ -s "$LOG" ]] || die "no events yet - run drills first (drills/drill.sh ...)"

SINCE="${1:-$(head -1 "$LOG" | cut -d'|' -f1)}"
[[ "$SINCE" == "today" ]] && SINCE="$(date -u +%Y-%m-%dT00:00:00Z)"
DAY="$(date -u -d "$SINCE" +%Y-%m-%d)"
OUT="$REPO_ROOT/docs/gameday/${DAY}.md"
mkdir -p "$(dirname "$OUT")"
epoch() { date -u -d "$1" +%s; }

# Alarm state changes in all three regions -> "ts|region|alarm|from|to"
ALARMS="$(mktemp)"
for region in ap-southeast-2 ap-southeast-4 us-east-1; do
  aws cloudwatch describe-alarm-history --region "$region" --history-item-type StateUpdate \
    --start-date "$SINCE" --max-items 500 --output json 2>/dev/null \
  | jq -r --arg r "$region" '.AlarmHistoryItems[]
      | select(.AlarmName | startswith("tflab-"))
      | (.HistorySummary | capture("from (?<f>[A-Z_]+) to (?<t>[A-Z_]+)")) as $s
      | "\(.Timestamp)|\($r)|\(.AlarmName)|\($s.f)|\($s.t)"' >> "$ALARMS"
done
sort -o "$ALARMS" "$ALARMS"

# Drill windows: each drill runs until the next drill starts (or now)
mapfile -t DRILLS < <(awk -F'|' -v s="$SINCE" '$1 >= s && $2 ~ /^drill:/' "$LOG")
now=$(date -u +%Y-%m-%dT%H:%M:%SZ)

{
  echo "# Game day ${DAY}"
  echo
  echo "Generated by \`drills/report.sh\` from \`.gameday/events.log\` and CloudWatch alarm history (Sydney, Melbourne, us-east-1)."
  echo "Times are UTC. *Detect* = drill start to first ALARM; *Recover* = drill start to that alarm returning to OK."
  echo
  echo "## Drills"
  echo
  echo "| Start (UTC) | Drill | Region | Alarms fired | Detect | Recover |"
  echo "|---|---|---|---|---|---|"
  for i in "${!DRILLS[@]}"; do
    IFS='|' read -r t ev reg _ <<<"${DRILLS[$i]}"
    next=$now; [[ $((i + 1)) -lt ${#DRILLS[@]} ]] && next=$(cut -d'|' -f1 <<<"${DRILLS[$((i + 1))]}")
    t0=$(epoch "$t")
    fired=""; detect="-"; recover="-"
    while IFS='|' read -r at ar an af atgt; do
      [[ -z "$at" ]] && continue
      [[ "$at" < "$t" || ! "$at" < "$next" ]] && continue
      if [[ "$atgt" == "ALARM" ]]; then
        d=$(( $(epoch "$at") - t0 ))
        fired+="\`${an}\` ($ar) "
        [[ "$detect" == "-" ]] && detect="${d}s"
      elif [[ "$af" == "ALARM" && "$atgt" == "OK" && "$recover" == "-" ]]; then
        recover="$(( $(epoch "$at") - t0 ))s"
      fi
    done < "$ALARMS"
    echo "| ${t:11:8} | ${ev#drill:} | $reg | ${fired:-none} | $detect | $recover |"
  done
  echo
  echo "## Recovery objectives (target RTO 900 s, RPO 15 min)"
  echo
  echo "| Time (UTC) | Event | Result |"
  echo "|---|---|---|"
  awk -F'|' -v s="$SINCE" '$1 >= s && $2 !~ /^drill:/ { printf "| %s | %s | %s |\n", substr($1,12,8), $2, ($4 == "" ? "-" : $4) }' "$LOG"
  echo
  echo "## All alarm transitions"
  echo
  echo "| Time (UTC) | Region | Alarm | Change |"
  echo "|---|---|---|---|"
  while IFS='|' read -r at ar an af atgt; do
    [[ -n "$at" ]] && echo "| ${at:11:8} | $ar | \`$an\` | $af → $atgt |"
  done < "$ALARMS"
  echo
  echo "## Notes"
  echo
  echo "- Observed vs expected: compare with \`.claude/skills/tflab-aws/drills.md\`; log differences in \`improve.md\` > Findings."
} > "$OUT"

rm -f "$ALARMS"
ok "wrote ${OUT#"$REPO_ROOT"/}"
echo "   commit it: git add docs/gameday && git commit -m \"Game day ${DAY} evidence\""
